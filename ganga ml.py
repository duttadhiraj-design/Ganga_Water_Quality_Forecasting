def build_supervised_dataset(panel_df):
    df = panel_df.sort_values(["stn_code", "time_step"]).reset_index(drop=True).copy()

    # Historical lags at time t (zero future leakage)
    df["DO_lag1"] = df.groupby("stn_code")["DO"].shift(1)
    df["DO_lag2"] = df.groupby("stn_code")["DO"].shift(2)
    df["BOD_lag1"] = df.groupby("stn_code")["BOD"].shift(1)
    df["pH_lag1"] = df.groupby("stn_code")["pH"].shift(1)

    # First-order DO change only when t-1 is immediately contiguous (gap == 1 round)
    df["lag1_gap"] = df["time_step"] - df.groupby("stn_code")["time_step"].shift(1)
    df["DO_diff1"] = np.where(df["lag1_gap"] == 1, df["DO"] - df["DO_lag1"], np.nan)

    # Organic oxygen demand ratio at time t
    df["BOD_to_DO_ratio"] = df["BOD"] / (df["DO"] + 1e-5)

    # Cyclical seasonality encoding across 24 half-month rounds
    df["sin_season"] = np.sin(2 * np.pi * df["period_idx"] / 24.0)
    df["cos_season"] = np.cos(2 * np.pi * df["period_idx"] / 24.0)

    # Target: Next consecutive sampling round DO (t + 1)
    df["Target_DO_next"] = df.groupby("stn_code")["DO"].shift(-1)
    df["Target_time_step"] = df.groupby("stn_code")["time_step"].shift(-1)
    df["Target_year"] = df.groupby("stn_code")["year"].shift(-1)

    # Keep only consecutive 1-round pairs where both DO_t and DO_{t+1} exist
    supervised = df[
        (df["Target_time_step"] == df["time_step"] + 1)
        & (df["DO"].notna())
        & (df["Target_DO_next"].notna())
    ].copy().reset_index(drop=True)

    return supervised


