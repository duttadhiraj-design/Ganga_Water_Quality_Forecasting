sns.set_theme(style="whitegrid")

for cfg in params_config:
    tgt = cfg["target"]
    unit = cfg["unit"]

    # Load and prepare panel
    panel = pd.read_csv("ganga_cleaned_panel.csv").sort_values(["stn_code", "time_step"]).reset_index(drop=True)
    panel[f"{tgt}_lag1"] = panel.groupby("stn_code")[tgt].shift(1)
    panel["lag1_gap"] = panel["time_step"] - panel.groupby("stn_code")["time_step"].shift(1)
    panel[f"{tgt}_diff1"] = np.where(panel["lag1_gap"] == 1, panel[tgt] - panel[f"{tgt}_lag1"], np.nan)
    panel["BOD_to_DO_ratio"] = panel["BOD"] / (panel["DO"] + 1e-5)
    panel["sin_season"] = np.sin(2 * np.pi * panel["period_idx"] / 24.0)
    panel["cos_season"] = np.cos(2 * np.pi * panel["period_idx"] / 24.0)

    panel[f"Target_{tgt}_next"] = panel.groupby("stn_code")[tgt].shift(-1)
    panel["Target_time_step"] = panel.groupby("stn_code")["time_step"].shift(-1)
    panel["Target_year"] = panel.groupby("stn_code")["year"].shift(-1)

    sup = panel[(panel["Target_time_step"] == panel["time_step"] + 1) & panel[tgt].notna() & panel[f"Target_{tgt}_next"].notna()].copy().reset_index(drop=True)

    # Chronological Split
    train_df = sup[sup["Target_year"] <= 2023].copy()
    val_df   = sup[sup["Target_year"] == 2024].copy()
    test_df  = sup[sup["Target_year"] == 2025].copy()

    num_cols = [tgt, "DO", "BOD", "pH", f"{tgt}_lag1", f"{tgt}_diff1", "BOD_to_DO_ratio", "sin_season", "cos_season"]
    prep = ColumnTransformer([
        ("num", Pipeline([("imp", SimpleImputer(strategy="median")), ("sc", StandardScaler())]), num_cols),
        ("cat", OneHotEncoder(drop="first", sparse_output=False), ["state"]),
    ])

    X_tr_raw, y_tr = prep.fit_transform(train_df), train_df[f"Target_{tgt}_next"].values
    X_va_raw, y_va = prep.transform(val_df), val_df[f"Target_{tgt}_next"].values
    X_te_raw, y_te = prep.transform(test_df), test_df[f"Target_{tgt}_next"].values

    X_tr = np.column_stack([np.ones(len(X_tr_raw)), X_tr_raw])
    X_va = np.column_stack([np.ones(len(X_va_raw)), X_va_raw])
    X_te = np.column_stack([np.ones(len(X_te_raw)), X_te_raw])

    # Train Models
    ols = LinearRegression().fit(X_tr_raw, y_tr)
    best_lam = 0.01

    def mse_l2(w):
        r = X_tr @ w - y_tr
        reg = np.r_[0.0, w[1:]]
        return 0.5 * np.mean(r**2) + 0.5 * best_lam * np.sum(reg**2), (X_tr.T @ r) / len(y_tr) + best_lam * reg

    w_cg = minimize(mse_l2, np.zeros(X_tr.shape[1]), jac=True, method="CG").x

    w_sub = np.zeros(X_tr.shape[1])
    for ep in range(1, 800):
        r = X_tr @ w_sub - y_tr
        g = (X_tr.T @ np.sign(r)) / len(y_tr) + 0.001 * np.r_[0.0, w_sub[1:]]
        w_sub -= ((0.3 / np.sqrt(ep)) / (np.linalg.norm(g) + 1e-8)) * g

    best_dt = DecisionTreeRegressor(max_depth=4, min_samples_leaf=15, random_state=42).fit(X_tr_raw, y_tr)
    best_rf = RandomForestRegressor(n_estimators=100, max_depth=6, min_samples_leaf=5, random_state=42).fit(X_tr_raw, y_tr)
    best_gb = GradientBoostingRegressor(loss="absolute_error", n_estimators=150, max_depth=3, learning_rate=0.03, random_state=42).fit(X_tr_raw, y_tr)

    results = {
        "Persistence (B1)": mean_absolute_error(y_te, test_df[tgt].values),
        "OLS Linear": mean_absolute_error(y_te, ols.predict(X_te_raw)),
        "Conjugate Grad (L2)": mean_absolute_error(y_te, X_te @ w_cg),
        "Subgradient (L1)": mean_absolute_error(y_te, X_te @ w_sub),
        "Decision Tree": mean_absolute_error(y_te, best_dt.predict(X_te_raw)),
        "Random Forest": mean_absolute_error(y_te, best_rf.predict(X_te_raw)),
        "Gradient Boosting": mean_absolute_error(y_te, best_gb.predict(X_te_raw))
    }

