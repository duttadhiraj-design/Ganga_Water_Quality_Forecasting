def clean_val(v):
    """Parse numeric water-quality readings, handling '-' and '1 (BDL)' tokens."""
    if pd.isna(v):
        return np.nan
    s = str(v).strip()
    if s in ["", "-", "NA", "N/A", "nan", "None"]:
        return np.nan
    # Extract leading numeric value (e.g., '1 (BDL)' -> 1.0)
    match = re.match(r"^([0-9]*\.?[0-9]+)", s)
    return float(match.group(1)) if match else np.nan


