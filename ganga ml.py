def extract_all_records(files_dict):
    records = []
    for param, fname in files_dict.items():
        xls = pd.ExcelFile(fname)
        for sheet in xls.sheet_names:
            state_code = sheet.split("_")[0]  # 'UK', 'UP', or 'WB'
            df = pd.read_excel(xls, sheet_name=sheet, header=None)
            current_year = None
            ncols = df.shape[1]

            for r in range(len(df)):
                c0 = str(df.iloc[r, 0]).strip() if pd.notna(df.iloc[r, 0]) else ""
                # Detect year header block: e.g., "... Year 2025"
                if "Manual Water Quality" in c0:
                    ym = re.search(r"Year\s+(\d{4})", c0)
                    if ym:
                        current_year = int(ym.group(1))
                    continue

                # Check if row is a valid station record (Sr.No 1..20)
                try:
                    sr = int(float(c0))
                except ValueError:
                    continue

                if 1 <= sr <= 20 and current_year is not None:
                    stn_code = str(df.iloc[r, 1]).strip().replace(".0", "")
                    stn_name = str(df.iloc[r, 2]).strip()

                    # 26-column sheets (UK_DO, UP_DO) start at Jan Round 2 (period_idx = 1)
                    # 27-column sheets start at Jan Round 1 (period_idx = 0)
                    offset = 2 if ncols == 26 else 3

                    for c in range(3, ncols):
                        p_idx = c - offset
                        month = (p_idx // 2) + 1
                        rnd = (p_idx % 2) + 1
                        val = clean_val(df.iloc[r, c])

                        records.append({
                            "state": state_code,
                            "stn_code": stn_code,
                            "stn_name": stn_name,
                            "year": current_year,
                            "month": month,
                            "round": rnd,
                            "period_idx": p_idx,
                            "param": param,
                            "val": val,
                        })
    return pd.DataFrame(records)


